@lru_cache(maxsize=1)
def _opencc_converter():
    try:
        from opencc import OpenCC
    except ImportError:
        return None
    return OpenCC("t2s")


def to_simplified_chinese(text: str) -> str:
    converter = _opencc_converter()
    if converter:
        text = converter.convert(text)
    else:
        text = text.translate(_COMMON_T2S)
    for source, target in _ASR_NORMALIZATION.items():
        text = text.replace(source, target)
    return text
